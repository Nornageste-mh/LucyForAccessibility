#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the d3dx9_40 proxy forwarding layer (src/forward.cpp).

The game imports d3dx9_40.dll by name, so our proxy must export exactly the same
undecorated export names.  Every export is a trampoline that jumps through a
pointer filled in once the real DLL (d3dx9_40_orig.dll, shipped alongside) is
loaded.  Until then each export points at a per-name lazy resolver, because we
are loaded from the game's own loader lock and must not LoadLibrary inside
DllMain; the first real call comes from a game thread after the lock is gone.

No game data is embedded: only the public Direct3D API name list, extracted from
the locally installed original DLL.

usage:
  python gen_forward.py --dll "<game>\\d3dx9_40.dll" --out ..\\src
"""
import argparse
import os

import pefile

HOOKED = [
    "D3DXCreateFontW",
    "D3DXCreateFontA",
    "D3DXCreateFontIndirectW",
    "D3DXCreateFontIndirectA",
]


def read_exports(path):
    pe = pefile.PE(path, fast_load=True)
    pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_EXPORT"]])
    names = [e.name.decode("ascii") for e in pe.DIRECTORY_ENTRY_EXPORT.symbols if e.name]
    machine = pe.FILE_HEADER.Machine
    if machine != 0x14C:
        raise SystemExit("expected x86 PE (0x14C), got 0x%X" % machine)
    pe.close()
    if not names:
        raise SystemExit("no named exports found")
    return sorted(set(names))


def gen(names, outdir):
    L = []
    a = L.append
    a("// GENERATED by tools/gen_forward.py -- do not edit by hand.")
    a("// Export surface of the original d3dx9_40.dll (%d names)." % len(names))
    a("#include <windows.h>")
    a("")
    a('extern "C" {')
    for n in names:
        a("void* p_%s = 0;" % n)
    a("}")
    a("")
    for n in names:
        a('static const char name_%s[] = "%s";' % (n, n))
    a("")
    a('extern "C" void* proxy_resolve(const char* name);   // proxy.cpp')
    a("")
    a("// Lazy trampoline used before the original DLL is resolved.")
    for n in names:
        a("static void __declspec(naked) lazy_%s(void)" % n)
        a("{")
        a("    __asm {")
        a("        push offset name_%s" % n)
        a("        call proxy_resolve")
        a("        add  esp, 4")
        a("        jmp  eax")
        a("    }")
        a("}")
    a("")
    a("struct FwdEntry { const char* name; void** slot; };")
    a('extern "C" const FwdEntry g_fwd[] = {')
    for n in names:
        a('    { "%s", &p_%s },' % (n, n))
    a("    { 0, 0 }")
    a("};")
    a("")
    a('extern "C" void forward_install_defaults(void)')
    a("{")
    for n in names:
        a("    if (!p_%s) { p_%s = (void*)&lazy_%s; }" % (n, n, n))
    a("}")
    a("")
    a("// The exported API itself: one plain jump per name.")
    a('extern "C" {')
    for n in names:
        a('__declspec(dllexport) void __declspec(naked) %s(void)' % n)
        a("{")
        a("    __asm {")
        a("        jmp dword ptr [p_%s]" % n)
        a("    }")
        a("}")
        a("")
    a("}")
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "forward.cpp"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L))
    with open(os.path.join(outdir, "exports_expected.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(names) + "\n")
    print("wrote forward.cpp: %d exports (%d hooked)" % (len(names), len(HOOKED)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dll", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    gen(read_exports(args.dll), args.out)


if __name__ == "__main__":
    main()
